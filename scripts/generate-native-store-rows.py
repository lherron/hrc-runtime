#!/usr/bin/env python3
"""Generate typed SQL row codecs from the reviewed canonical Bun scratch observation.

This is a build-time source tool, never a runtime schema guard/migrator. Shadow
FTS tables remain SQLite-owned; repositories operate on the external-content table.
"""
import json
import pathlib

root = pathlib.Path(__file__).resolve().parents[1]
schema = json.loads((root/'contract/hrc-parity/store-schema.json').read_text())
domain = ['//! Canonical SQL row shapes; generated by scripts/generate-native-store-rows.py.',
          '//! Wire/domain mappings are deliberately implemented by typed repositories.',
          'use serde::{Deserialize, Serialize};', '']
code = ['// Generated typed row codecs. No arbitrary SQL or table API is public.',
        'use hrc_domain::store::rows::*;', 'use rusqlite::{Row, types::Value};',
        'pub(crate) trait RowCodec: Sized {', '    const COLUMNS: &\'static str;',
        '    fn decode(row: &Row<\'_>) -> rusqlite::Result<Self>;',
        '    fn values(&self) -> Vec<Value>;', '}', '']
for table in schema['tables']:
    name = table['name']
    if name.startswith('transcript_turns_fts'):
        continue
    typ = ''.join(w.capitalize() for w in name.split('_'))+'Row'
    columns = table['columns']
    domain.extend(['#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]', '#[serde(rename_all = "camelCase")]', 'pub struct '+typ+' {'])
    for col in columns:
        sqltype = col['type'].upper()
        rust = 'i64' if 'INT' in sqltype else 'f64' if any(t in sqltype for t in ['REAL','FLOAT','DOUBLE']) else 'Vec<u8>' if sqltype=='BLOB' else 'String'
        optional = not col['notnull'] and not col['pk']
        if optional: domain.append('    #[serde(skip_serializing_if = "Option::is_none")]')
        if name == 'inputs' and col['name'] == 'terminal_kind': domain.append('    #[serde(rename = "terminal")]')
        domain.append('    pub '+('r#'+col['name'] if col['name'] in ['type','match','ref'] else col['name'])+': '+('Option<'+rust+'>' if optional else rust)+',')
    domain.extend(['}', ''])
    code.extend(['impl RowCodec for '+typ+' {','    const COLUMNS: &\'static str = "'+', '.join('"'+c['name']+'"' for c in columns).replace('"','\\"')+'";',
                 '    fn decode(row: &Row<\'_>) -> rusqlite::Result<Self> {', '        Ok(Self {'])
    for c in columns:
        field = 'r#'+c['name'] if c['name'] in ['type','match','ref'] else c['name']
        code.append('            '+field+': row.get("'+c['name']+'")?,')
    code.extend(['        })', '    }', '    fn values(&self) -> Vec<Value> {', '        vec!['])
    for c in columns:
        field = 'r#'+c['name'] if c['name'] in ['type','match','ref'] else c['name']
        copy = 'INT' in c['type'].upper() or any(t in c['type'].upper() for t in ['REAL','FLOAT','DOUBLE'])
        code.append('            self.'+field+('' if copy else '.clone()')+'.into(),')
    code.extend(['        ]', '    }', '}', ''])
(root/'crates/hrc-domain/src/store/rows.rs').write_text('\n'.join(domain))
(root/'crates/hrc-store/src/row_codec.rs').write_text('\n'.join(code))
